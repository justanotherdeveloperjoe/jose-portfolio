// Builds src/data/skyline.js: Monterrey's real skyline, seen from the coordinates printed on the playground poster.
// Elevation: AWS Terrain Tiles (skadi), from INEGI Continental relief 2016 and USGS SRTM. Tiles are cached in .cache/terrain.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cache = join(root, '.cache', 'terrain');
const viewpoint = { lat: 25.6866, lon: -100.3161, eye: 30 };
const view = { from: 60, to: 300, step: 0.25 };
const bands = { near: [400, 3500], mid: [3500, 14000], far: [14000, 60000] };
const earth = 6371000 / (1 - 0.13); // effective radius with standard refraction
const tiles = new Map();

async function loadTile(lat, lon) {
  const name = `${lat < 0 ? 'S' : 'N'}${String(Math.abs(lat)).padStart(2, '0')}${lon < 0 ? 'W' : 'E'}${String(Math.abs(lon)).padStart(3, '0')}`;
  const file = join(cache, `${name}.hgt.gz`);
  let gz;
  try { gz = await readFile(file); } catch {
    const response = await fetch(`https://s3.amazonaws.com/elevation-tiles-prod/skadi/${name.slice(0, 3)}/${name}.hgt.gz`);
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    gz = Buffer.from(await response.arrayBuffer());
    await mkdir(cache, { recursive: true });
    await writeFile(file, gz);
  }
  const raw = gunzipSync(gz), size = Math.sqrt(raw.length / 2);
  if (!Number.isInteger(size)) throw new Error(`${name}: unexpected size ${raw.length}`);
  tiles.set(`${lat},${lon}`, { lat, lon, size, raw });
}

function sample(tile, row, col) {
  const value = tile.raw.readInt16BE(2 * (row * tile.size + col));
  return value === -32768 ? null : value;
}

function elevation(lat, lon) {
  const tile = tiles.get(`${Math.floor(lat)},${Math.floor(lon)}`);
  if (!tile) return null;
  const y = (tile.lat + 1 - lat) * (tile.size - 1), x = (lon - tile.lon) * (tile.size - 1);
  const row = Math.min(Math.floor(y), tile.size - 2), col = Math.min(Math.floor(x), tile.size - 2), fy = y - row, fx = x - col;
  const corners = [[sample(tile, row, col), (1 - fx) * (1 - fy)], [sample(tile, row, col + 1), fx * (1 - fy)], [sample(tile, row + 1, col), (1 - fx) * fy], [sample(tile, row + 1, col + 1), fx * fy]].filter(([value]) => value !== null);
  const weight = corners.reduce((sum, [, w]) => sum + w, 0);
  return weight ? corners.reduce((sum, [value, w]) => sum + value * w, 0) / weight : null;
}

for (const [lat, lon] of [[25, -101], [25, -100]]) await loadTile(lat, lon);
const ground = elevation(viewpoint.lat, viewpoint.lon), eye = ground + viewpoint.eye;
const metersPerDegree = 111320, lonScale = Math.cos(viewpoint.lat * Math.PI / 180);
const profile = Object.fromEntries(Object.keys(bands).map(name => [name, []]));
const peaks = Object.fromEntries(Object.keys(bands).map(name => [name, { angle: -90 }]));

for (let az = view.from; az <= view.to + 1e-9; az += view.step) {
  const best = Object.fromEntries(Object.keys(bands).map(name => [name, { angle: -90 }]));
  const north = Math.cos(az * Math.PI / 180), east = Math.sin(az * Math.PI / 180);
  for (let d = bands.near[0]; d <= bands.far[1]; d += Math.max(25, d * 0.003)) {
    const h = elevation(viewpoint.lat + d * north / metersPerDegree, viewpoint.lon + d * east / (metersPerDegree * lonScale));
    if (h === null) break;
    const angle = Math.atan2(h - eye - d * d / (2 * earth), d) * 180 / Math.PI;
    const band = Object.keys(bands).find(name => d >= bands[name][0] && d < bands[name][1]);
    if (band && angle > best[band].angle) best[band] = { angle, distance: d, height: h };
  }
  for (const name of Object.keys(bands)) {
    profile[name].push(Math.round(best[name].angle * 100) / 100);
    if (best[name].angle > peaks[name].angle) peaks[name] = { ...best[name], azimuth: az };
  }
}

const data = { viewpoint: { lat: viewpoint.lat, lon: viewpoint.lon, ground: Math.round(ground) }, from: view.from, step: view.step, ...profile };
await writeFile(join(root, 'src', 'data', 'skyline.js'), `// Generated by scripts/build-skyline.mjs from INEGI and USGS SRTM elevation data. Do not edit by hand.\nexport const skyline = ${JSON.stringify(data)};\n`);
console.log(`Viewpoint ground ${Math.round(ground)} m; ${profile.near.length} azimuths per band.`);
for (const [name, peak] of Object.entries(peaks)) console.log(`${name}: highest ${peak.angle.toFixed(2)}° at ${peak.azimuth}°, ${(peak.distance / 1000).toFixed(1)} km, ${Math.round(peak.height)} m`);
