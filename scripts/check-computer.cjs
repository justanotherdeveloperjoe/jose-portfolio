const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.SANDBOX_URL || 'http://127.0.0.1:4173';

(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], outside = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://computer-test.invalid/**', route => { outside.push(route.request().url()); return route.abort(); });
    await page.goto(base);
    await page.getByRole('button', { name: 'Open sandbox' }).click();
    const input = page.locator('#sandbox-command');
    const run = async value => { await input.fill(value); await input.press('Enter'); };
    const output = page.locator('.computer-screen');
    await run('mkdir ideas');
    await run('echo "A computer I can use" > ideas/note.txt');
    await run('cat ideas/note.txt');
    assert.ok((await output.innerText()).includes('A computer I can use'));
    await run('cp ideas/note.txt ideas/copy.txt');
    await run('mv ideas/copy.txt ideas/renamed.txt');
    await run('rm ideas/renamed.txt');
    await run('cat ideas/renamed.txt');
    assert.match(await page.locator('.computer-entry').last().innerText(), /no such file/);
    await input.fill('cat read'); await input.press('Alt+ArrowRight');
    assert.equal(await input.inputValue(), 'cat readme.txt');
    await input.press('Tab');
    assert.notEqual(await page.evaluate(() => document.activeElement.id), 'sandbox-command', 'Tab must leave input');
    await run('edit hello.js');
    const editor = page.locator('#computer-file');
    await editor.fill('console.log("It works", [2, 3].map(n => n * 3));');
    await editor.press('Control+s');
    await editor.press('Escape');
    assert.equal(await input.evaluate(node => node === document.activeElement), true);
    await run('run hello.js');
    await output.getByText('Process finished.', { exact: true }).waitFor();
    assert.match(await output.innerText(), /It works \[6,9\]/);
    const finished = async code => {
      await run('clear'); await run('js ' + code);
      await output.getByText('Process finished.', { exact: true }).waitFor();
    };
    await finished('[1,2,3].reduce((a,b) => a+b, 0)');
    assert.match(await output.innerText(), /\n6\n/);
    await finished('typeof document + " / " + typeof window + " / " + typeof localStorage');
    assert.match(await output.innerText(), /undefined \/ undefined \/ undefined/);
    await finished('await fetch("https://computer-test.invalid/nope").then(()=>console.log("BAD"),()=>console.log("network blocked"))');
    assert.match(await output.innerText(), /network blocked/);
    await finished('try { importScripts("https://computer-test.invalid/script.js") } catch { console.log("imports blocked") }');
    assert.match(await output.innerText(), /imports blocked/);
    assert.deepEqual(outside, []);
    await run('clear'); await run('js while(true) {}');
    await output.getByText('Stopped: 2 second time limit reached.', { exact: true }).waitFor({ timeout: 5000 });
    assert.equal(await page.locator('iframe[title="Isolated JavaScript process"]').count(), 0);
    await run('clear'); await run('js while(true) {}');
    await input.press('Control+c');
    await output.getByText('Process stopped.', { exact: true }).waitFor();
    await run('js while(true) {}');
    await page.getByRole('button', { name: 'Close computer', exact: true }).click();
    await page.locator('iframe[title="Isolated JavaScript process"]').waitFor({ state: 'detached' });
    await page.getByRole('button', { name: 'Open sandbox' }).click();
    await run('cat ideas/note.txt');
    assert.match(await page.locator('.computer-entry').last().innerText(), /A computer I can use/);
    const download = page.waitForEvent('download');
    await run('download ideas/note.txt');
    assert.equal((await download).suggestedFilename(), 'note.txt');
    await page.reload();
    await page.getByRole('button', { name: 'Open sandbox' }).click();
    await run('cat ideas/note.txt');
    assert.match(await page.locator('.computer-entry').last().innerText(), /A computer I can use/);
    await run('run hello.js');
    await output.getByText('Process finished.', { exact: true }).waitFor();
    assert.match(await output.innerText(), /It works \[6,9\]/);
    await run('ls');
    await page.locator('#sandbox').screenshot({ path: '.preview/computer-desktop.png' });
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
      if (width === 390) await page.locator('#sandbox').screenshot({ path: '.preview/computer-mobile.png' });
    }
    await run('exit');
    await input.waitFor({ state: 'detached' });
    assert.deepEqual(errors, []);
    const blocked = await browser.newPage();
    await blocked.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new Error('Unavailable'); } }); });
    await blocked.goto(base);
    await blocked.getByRole('button', { name: 'Open sandbox' }).click();
    await blocked.getByText('Files saved for this session only', { exact: true }).waitFor();
    console.log('Computer file lifecycle, persistence, editor, JavaScript, network isolation, timeout/cancel, completion, downloads, responsive layout and storage fallback: PASS');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
