import assert from 'node:assert/strict';
import { prepareAssets, sampleAssetNames, toCsv, deliveryReducer, initialDelivery } from '../src/lib/learningTasks.js';

assert.deepEqual(prepareAssets(sampleAssetNames).map(file => file.path), ['images/homepage-hero.jpg', 'images/brand-logo.svg', 'images/team-portrait.png', 'documents/menu-summer.pdf', 'images/homepage-hero-2.jpg']);
assert.deepEqual(prepareAssets('café.JPG\ncafe.jpg\ncafe-2.jpg\nCAFE.JPG').map(file => file.path), ['images/cafe.jpg', 'images/cafe-2.jpg', 'images/cafe-2-2.jpg', 'images/cafe-3.jpg']);
assert.deepEqual(prepareAssets('C:\\drafts\\Hero.JPG\n../Brand.woff2\nREADME\n.env\n☕.png').map(file => file.path), ['images/hero.jpg', 'fonts/brand.woff2', 'other/readme', 'other/env', 'images/asset.png']);
assert.equal(prepareAssets('A Hero.JPG', { cleanNames: false, groupByType: false })[0].path, 'A Hero.jpg');
assert.throws(() => prepareAssets(' \n '), /at least one/);
assert.throws(() => prepareAssets('../'), /filenames/);
assert.throws(() => prepareAssets('..'), /filenames/);
assert.throws(() => prepareAssets(Array(51).fill('a.png').join('\n')), /50 filenames/);
const csv = toCsv(['before', 'after'], [['one,"two"', 'a\nb'], ['=1+1', null], [' @SUM(1)', 'safe']]);
assert.equal(csv, '"before","after"\r\n"one,""two""","a\nb"\r\n"\'=1+1",""\r\n"\' @SUM(1)","safe"');

let state = deliveryReducer(initialDelivery, 'visit');
assert.equal(state.outcome, 'miss');
assert.equal(state.cached, 1);
state = deliveryReducer(state, 'publish');
assert.equal(state.origin, 2);
state = deliveryReducer(state, 'visit');
assert.equal(state.visitor, 1, 'Publishing does not replace the cached response');
assert.equal(state.hits, 1);
state = deliveryReducer(state, 'invalidate');
assert.equal(state.cached, null);
assert.equal(state.visitor, 1, 'Invalidation does not retroactively change a page already viewed');
state = deliveryReducer(state, 'visit');
assert.equal(state.visitor, 2);
state = deliveryReducer(state, 'toggle-origin');
state = deliveryReducer(state, 'visit');
assert.equal(state.outcome, 'hit', 'A fresh edge copy can serve while the origin is unavailable');
assert.equal(deliveryReducer(state, 'publish').origin, 2, 'Cannot publish while origin is unavailable');
state = deliveryReducer(state, 'invalidate');
state = deliveryReducer(state, 'visit');
assert.equal(state.outcome, 'error');
assert.equal(state.visitor, null);
state = deliveryReducer(state, 'toggle-origin');
state = deliveryReducer(state, 'visit');
assert.equal(state.visitor, 2, 'Recovers after restoring the origin');
assert.equal(state.hits + state.fetches, state.requests);
assert.equal(state.requests, 6);
assert.deepEqual(deliveryReducer(state, 'reset'), initialDelivery);
assert.equal(initialDelivery.cached, null, 'Reducer never mutates its initial state');
console.log('Learning task checks passed: naming, duplicates, invalid input, CSV escaping, cache freshness, outage and recovery.');
