import assert from 'node:assert/strict';
import { createGame, stepGame, overlaps, GAME_WIDTH, GAME_HEIGHT } from '../src/components/spaceGame.js';
const idle = { left: false, right: false, fire: false };
const game = createGame();
assert.equal(game.enemies.length, 21);
for (let i = 0; i < 100; i++) stepGame(game, { ...idle, left: true }, .016, () => 0);
assert.equal(game.player.x, 16);
for (let i = 0; i < 200; i++) stepGame(game, { ...idle, right: true }, .016, () => 0);
assert.equal(game.player.x, GAME_WIDTH - game.player.w - 16);
const scoring = createGame();
const enemy = scoring.enemies[0];
scoring.shots.push({ x: enemy.x + 10, y: enemy.y + 7, w: 3, h: 9 });
stepGame(scoring, idle, .016, () => 0);
assert.equal(enemy.alive, false);
assert.equal(scoring.score, 30);
assert.equal(scoring.shots.length, 0);
scoring.enemies.forEach(e => { e.alive = false; });
stepGame(scoring, idle, .016, () => 0);
assert.ok(scoring.nextWave > 0);
for (let i = 0; i < 80; i++) stepGame(scoring, idle, .016, () => 0);
assert.equal(scoring.wave, 2);
assert.equal(scoring.enemies.filter(e => e.alive).length, 21);
const damage = createGame();
function hit() { damage.enemyShots.push({ x: damage.player.x + 5, y: damage.player.y - 2, w: 4, h: 10 }); stepGame(damage, idle, .01, () => 0); }
hit(); assert.equal(damage.lives, 2);
hit(); assert.equal(damage.lives, 2, 'Invulnerability prevents repeated damage');
damage.invulnerable = 0; hit();
damage.invulnerable = 0; hit();
assert.equal(damage.lives, 0); assert.equal(damage.state, 'over');
const frozen = JSON.stringify(damage); stepGame(damage, { ...idle, fire: true }, .04);
assert.equal(JSON.stringify(damage), frozen);
const invasion = createGame(); invasion.enemies[0].y = invasion.player.y;
stepGame(invasion, idle, .01); assert.equal(invasion.state, 'over');
const cleanup = createGame(); cleanup.shots.push({ x: 10, y: -20, w: 3, h: 9 }); cleanup.enemyShots.push({ x: 10, y: GAME_HEIGHT + 20, w: 4, h: 10 });
stepGame(cleanup, idle, .01); assert.equal(cleanup.shots.length, 0); assert.equal(cleanup.enemyShots.length, 0);
assert.equal(overlaps({ x: 0, y: 0, w: 10, h: 10 }, { x: 9, y: 9, w: 10, h: 10 }), true);
console.log('Movement limits, hitboxes, score, wave progression, damage immunity, game-over, projectile cleanup: PASS');
